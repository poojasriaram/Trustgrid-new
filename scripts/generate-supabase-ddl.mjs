import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const csvPath = path.join(ROOT_DIR, 'data', 'sheet1.csv');
const content = fs.readFileSync(csvPath, 'utf8');
const lines = content.split('\n').filter(l => l.trim().length > 0);
const headers = lines[0].split(',').map(h => h.trim());

// Create robust PostgreSQL DDL
// Using TEXT or safe types to prevent insert failures on varied formats, with clean defaults
let ddl = `-- =========================================================================
-- TRUSTGRID.AI — SUPABASE DATABASE MIGRATION SCHEMA
-- Project Ref: ndalgvpvpzwrqoikkpyb
-- Generated for Master 95-Column Live Traffic Events & Behavioral Telemetry
-- =========================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

DROP TABLE IF EXISTS public.live_traffic_events CASCADE;

CREATE TABLE public.live_traffic_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  migrated_at TIMESTAMPTZ DEFAULT NOW(),
`;

const columnsSQL = headers.map(h => {
  return `  "${h}" TEXT`;
});

ddl += columnsSQL.join(',\n');
ddl += `
);

-- Indexes for lightning fast analytics queries
CREATE INDEX IF NOT EXISTS idx_lte_timestamp ON public.live_traffic_events ("timestamp");
CREATE INDEX IF NOT EXISTS idx_lte_session_id ON public.live_traffic_events ("session_id");
CREATE INDEX IF NOT EXISTS idx_lte_user_id ON public.live_traffic_events ("user_id");
CREATE INDEX IF NOT EXISTS idx_lte_event_name ON public.live_traffic_events ("event_name");
CREATE INDEX IF NOT EXISTS idx_lte_page ON public.live_traffic_events ("page");

-- Enable Row Level Security (RLS)
ALTER TABLE public.live_traffic_events ENABLE ROW LEVEL SECURITY;

-- Allow inserts and reads for both anon / publishable key and service role
CREATE POLICY "Allow public insert" ON public.live_traffic_events
  FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public select" ON public.live_traffic_events
  FOR SELECT USING (true);
`;

const outPath = path.join(ROOT_DIR, 'data', 'create_supabase_tables.sql');
fs.writeFileSync(outPath, ddl, 'utf8');
console.log('✅ Generated DDL at:', outPath);

