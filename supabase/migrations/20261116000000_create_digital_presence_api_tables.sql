-- 1. Analytics Events (/api/analytics/events, /api/analytics/dashboard, /api/analytics/reports/export)
CREATE TABLE IF NOT EXISTS public.analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id TEXT NOT NULL UNIQUE,
  event_name TEXT NOT NULL,
  event_category TEXT DEFAULT 'general',
  event_action TEXT DEFAULT 'action',
  session_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  timestamp_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  page_path TEXT NOT NULL,
  page_title TEXT DEFAULT '',
  referrer TEXT DEFAULT '',
  traffic_source TEXT DEFAULT 'Direct',
  utm_source TEXT DEFAULT '',
  utm_medium TEXT DEFAULT '',
  utm_campaign TEXT DEFAULT '',
  utm_term TEXT DEFAULT '',
  utm_content TEXT DEFAULT '',
  device_type TEXT DEFAULT 'Desktop',
  operating_system TEXT DEFAULT 'Unknown',
  browser TEXT DEFAULT 'Unknown',
  screen_res TEXT DEFAULT '',
  country TEXT DEFAULT 'Unknown',
  country_code TEXT DEFAULT 'XX',
  region TEXT DEFAULT 'Unknown',
  city TEXT DEFAULT 'Unknown',
  timezone_browser TEXT DEFAULT 'UTC',
  timezone_ip TEXT DEFAULT 'UTC',
  ip_masked TEXT DEFAULT '0.0.***.***',
  asn TEXT DEFAULT 'Unknown',
  organization TEXT DEFAULT 'Unknown',
  isp TEXT DEFAULT 'Unknown',
  is_bounce INTEGER DEFAULT 0,
  is_conversion INTEGER DEFAULT 0,
  conversion_goal TEXT DEFAULT '',
  dwell_time_sec INTEGER DEFAULT 0,
  scroll_depth INTEGER DEFAULT 0,
  metadata_json JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_supa_events_session ON public.analytics_events(session_id);
CREATE INDEX IF NOT EXISTS idx_supa_events_user ON public.analytics_events(user_id);
CREATE INDEX IF NOT EXISTS idx_supa_events_timestamp ON public.analytics_events(timestamp_utc DESC);
CREATE INDEX IF NOT EXISTS idx_supa_events_name ON public.analytics_events(event_name);
CREATE INDEX IF NOT EXISTS idx_supa_events_page ON public.analytics_events(page_path);

-- 2. Analytics Sessions (/api/analytics/events, /api/analytics/dashboard, /api/analytics/reports/export)
