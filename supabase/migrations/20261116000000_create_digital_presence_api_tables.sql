  traffic_source TEXT DEFAULT 'Direct',
  utm_campaign TEXT DEFAULT '',
  country TEXT DEFAULT 'Unknown',
  city TEXT DEFAULT 'Unknown',
  timezone_browser TEXT DEFAULT 'UTC',
